#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Dot {
    pub x: i32,
    pub y: i32,
}

pub struct Wordmark {
    pub columns: i32,
    pub dots: Vec<Dot>,
}

/// The same local 5×7 glyphs as the HTTP manager, computed once at startup.
/// Names outside the readable matrix range keep their original plain text.
pub fn wordmark(name: &str) -> Option<Wordmark> {
    if name.is_empty()
        || name.len() > 8
        || !name.bytes().all(|letter| letter.is_ascii_alphanumeric())
    {
        return None;
    }
    let mut dots = Vec::new();
    for (index, letter) in name.bytes().enumerate() {
        let glyph = match letter {
            b'a'..=b'z' => usize::from(letter - b'a'),
            b'A'..=b'Z' => usize::from(letter - b'A') + 26,
            b'0'..=b'9' => usize::from(letter - b'0') + 52,
            _ => unreachable!("validated ASCII product name"),
        };
        for (y, row) in GLYPHS[glyph].iter().enumerate() {
            for x in 0..5 {
                if row & (1 << (4 - x)) != 0 {
                    dots.push(Dot {
                        x: index as i32 * 6 + x,
                        y: y as i32,
                    });
                }
            }
        }
    }
    Some(Wordmark {
        columns: name.len() as i32 * 6 - 1,
        dots,
    })
}

